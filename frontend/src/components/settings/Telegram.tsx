import { useEffect, useMemo, useState } from 'react';
import { Eye, EyeOff, Send, Layers } from 'lucide-react';
import { cn } from '@/lib/cn';
import { getTenantMode } from '@/lib/api';
import { useTelegramConfig } from '@/lib/queries';
import { useSaveTelegram, useTestTelegram, useCreateTelegramTopics } from '@/lib/mutations';
import type { TelegramCategory, TelegramInput, AdminEventType } from '@/lib/types';
import { Button, LoadingState, Input, Field } from '@/components/ui';

const TG_CATEGORIES: { key: string; label: string }[] = [
  { key: 'resources', label: 'Resources & routing' },
  { key: 'networks', label: 'Networks' },
  { key: 'policies', label: 'Policies' },
  { key: 'inventory', label: 'Peers & Groups' },
  { key: 'automation', label: 'Automation' },
  { key: 'settings', label: 'Settings, filters & access' },
  { key: 'requests', label: 'Access requests (approve/deny)' },
  { key: 'alerts', label: 'Security alerts (anomalies)' },
];

// NetBird activity is split into its own topics by kind (keys match netbirdSubcategory()).
const TG_NB_CATEGORIES: { key: string; label: string }[] = [
  { key: 'nb_peers', label: 'Peers' },
  { key: 'nb_users', label: 'Users & access' },
  { key: 'nb_groups', label: 'Groups' },
  { key: 'nb_policies', label: 'Policies & posture' },
  { key: 'nb_keys', label: 'Setup keys' },
  { key: 'nb_network', label: 'Network & DNS' },
  { key: 'nb_other', label: 'Other' },
];

const TG_ENV_HINT = 'Managed by the TELEGRAM_BOT_TOKEN environment variable - edit it in your deployment config, not here.';
const topicInputCls = 'w-28 h-8 shrink-0 rounded-md border px-2.5 text-sm font-mono bg-white border-nb-gray-200 dark:bg-nb-gray-900 dark:border-nb-gray-700 dark:text-nb-gray-100 outline-none focus:border-netbird/60';

// Origin of each selectable notification: generated by THIS APP, or forwarded NetBird activity.
function SourceTag({ kind }: { kind: 'app' | 'netbird' }) {
  return kind === 'app'
    ? <span title="Generated by this app (audit actions, request flows, alerts)" className="inline-flex items-center rounded border border-netbird/40 bg-netbird/10 px-1.5 py-0.5 text-[0.64rem] font-semibold uppercase tracking-wide text-netbird shrink-0">App</span>
    : <span title="NetBird activity event, forwarded as-is from your NetBird account" className="inline-flex items-center rounded border border-sky-500/40 bg-sky-500/10 px-1.5 py-0.5 text-[0.64rem] font-semibold uppercase tracking-wide text-sky-500 dark:text-sky-400 shrink-0">NetBird</span>;
}

export function Telegram() {
  const inTenantMode = !!getTenantMode();
  const { data, isLoading } = useTelegramConfig();
  const save = useSaveTelegram();
  const test = useTestTelegram();
  const createTopics = useCreateTelegramTopics();
  const [enabled, setEnabled] = useState(false);
  const [chatId, setChatId] = useState('');
  const [token, setToken] = useState('');
  const [showToken, setShowToken] = useState(false);
  const [cats, setCats] = useState<Record<string, TelegramCategory>>({});
  const [events, setEvents] = useState<string[]>([]);
  // Main only: mirror managed tenants' activity to main's Telegram (absent in tenant mode).
  const [tenantActivity, setTenantActivity] = useState(false);
  const [saved, setSaved] = useState(false);
  const [error, setError] = useState('');
  const [testMsg, setTestMsg] = useState('');

  useEffect(() => {
    if (data) {
      setEnabled(data.enabled);
      setChatId(data.chatId || '');
      setCats(data.categories || {});
      setEvents(data.netbirdEvents || []);
      setTenantActivity(!!data.tenantActivity);
    }
  }, [data]);

  const tokenLocked = !!data?.tokenFromEnv;
  const setCat = (key: string, patch: Partial<TelegramCategory>) => setCats((p) => ({ ...p, [key]: { ...p[key], ...patch } }));
  const toggleEvent = (msg: string) => setEvents((p) => (p.includes(msg) ? p.filter((m) => m !== msg) : [...p, msg]));

  const payload = (): TelegramInput => ({
    enabled, chatId: chatId.trim(), categories: cats, netbirdEvents: events, token: token.trim() || undefined,
    // Only round-trip tenantActivity from main - the field is absent in tenant mode.
    ...(inTenantMode ? {} : { tenantActivity }),
  });

  const onSave = async () => {
    setError(''); setTestMsg('');
    try { await save.mutateAsync(payload()); setToken(''); setSaved(true); setTimeout(() => setSaved(false), 2000); }
    catch (e) { setError((e as Error).message || 'Failed to save'); }
  };
  const onTest = async () => {
    setError(''); setTestMsg('');
    try {
      await save.mutateAsync(payload()); setToken(''); // save first so the test uses the latest values
      const r = await test.mutateAsync();
      setTestMsg(r.ok ? '✅ Test message sent.' : `❌ ${r.error || 'Failed to send'}`);
    } catch (e) { setError((e as Error).message || 'Test failed'); }
  };
  const onAutoTopics = async () => {
    setError(''); setTestMsg('');
    try {
      await save.mutateAsync(payload()); setToken(''); // persist token/chat/enables first
      const names: Record<string, string> = {};
      TG_CATEGORIES.forEach((c) => { names[c.key] = c.label; });
      TG_NB_CATEGORIES.forEach((c) => { names[c.key] = `NetBird · ${c.label}`; });
      const r = await createTopics.mutateAsync(names); // refetch (onSuccess) re-fills the topic IDs
      setTestMsg(r.ok ? `✅ Created ${r.created} topic(s).` : `⚠️ ${(r.errors && r.errors.join(' | ')) || 'Some topics failed - is the bot a group admin with “Manage Topics”?'}`);
    } catch (e) { setError((e as Error).message || 'Failed to create topics'); }
  };
  const noConn = (!data?.hasToken && !token.trim()) || !chatId.trim();

  // NetBird event types grouped by their sub-topic (so each kind shows under its own topic).
  const eventsByCat = useMemo(() => {
    const g: Record<string, AdminEventType[]> = {};
    (data?.eventTypes || []).forEach((t) => { const k = t.category || 'nb_other'; (g[k] = g[k] || []).push(t); });
    return g;
  }, [data?.eventTypes]);

  return (
    <div className="max-w-2xl">
      <p className="text-nb-gray-500 text-sm mb-5">
        Send notifications about actions taken in this app - and selected NetBird activity events - to a Telegram forum group,
        each category routed to its own topic. Create a bot via <span className="font-medium">@BotFather</span>, add it to the group as an admin,
        then paste its token and the group Chat ID below. The token is stored on the server and never shown again.
      </p>
      {inTenantMode && (
        <div className="mb-5 rounded-md border border-nb-gray-200 dark:border-nb-gray-800/70 bg-nb-gray-100/60 dark:bg-nb-gray-900/70 px-3.5 py-2.5 text-[0.8rem] text-nb-gray-600 dark:text-nb-gray-300">
          This configures <b>this tenant's own</b> Telegram notifications - its events and alerts are delivered here, to the tenant's own group.
        </div>
      )}
      {isLoading ? <LoadingState /> : (
        <div className="flex flex-col gap-5">
          <label className="flex items-center gap-3 p-3.5 rounded-md border border-nb-gray-200 dark:border-nb-gray-800 bg-nb-gray-50 dark:bg-nb-gray-900/30 cursor-pointer">
            <input type="checkbox" className="h-4 w-4 accent-netbird" checked={enabled} onChange={(e) => setEnabled(e.target.checked)} />
            <span className="text-sm">
              <span className="font-medium text-nb-gray-800 dark:text-nb-gray-100">Enable Telegram notifications</span>
              <span className="block text-nb-gray-500 text-[0.8rem]">Master switch - when off, nothing is sent regardless of the selections below.</span>
            </span>
          </label>

          {/* Main only: also forward managed tenants' activity to main's Telegram, tagged per tenant. */}
          {!inTenantMode && (
            <label className="flex items-center gap-3 p-3.5 rounded-md border border-nb-gray-200 dark:border-nb-gray-800 bg-nb-gray-50 dark:bg-nb-gray-900/30 cursor-pointer">
              <input type="checkbox" className="h-4 w-4 accent-netbird" checked={tenantActivity} onChange={(e) => setTenantActivity(e.target.checked)} />
              <span className="text-sm">
                <span className="font-medium text-nb-gray-800 dark:text-nb-gray-100">Tenant Activity</span>
                <span className="block text-nb-gray-500 text-[0.8rem]">Also send tenant audit and scheduler alerts to this account's Telegram, tagged with the tenant's name.</span>
              </span>
            </label>
          )}

          <Field label="Bot Token" hint={tokenLocked ? TG_ENV_HINT : data?.hasToken ? 'A token is configured. Leave blank to keep it, or enter a new one to replace it.' : 'Create a bot with @BotFather and paste the token it gives you.'}>
            <div className="relative">
              <Input
                type={showToken && !tokenLocked ? 'text' : 'password'}
                autoComplete="new-password"
                value={tokenLocked ? '' : token}
                onChange={(e) => setToken(e.target.value)}
                placeholder={tokenLocked ? '•••••••••••• (from environment)' : data?.hasToken ? '•••••••••••• (configured)' : '123456789:ABCdef…'}
                disabled={tokenLocked}
                className={cn('font-mono text-[0.82rem]', token && !tokenLocked && 'pr-10', tokenLocked && 'opacity-60 cursor-not-allowed')}
              />
              {token && !tokenLocked && (
                <button type="button" onClick={() => setShowToken((s) => !s)} title={showToken ? 'Hide' : 'Show'}
                  className="absolute right-2.5 top-1/2 -translate-y-1/2 text-nb-gray-400 hover:text-nb-gray-700 dark:hover:text-nb-gray-100">
                  {showToken ? <EyeOff size={15} /> : <Eye size={15} />}
                </button>
              )}
            </div>
          </Field>

          <Field label="Group Chat ID" hint="A forum (Topics-enabled) group, e.g. -1001234567890. Get it from @RawDataBot, or the group's Web Telegram URL.">
            <Input value={chatId} onChange={(e) => setChatId(e.target.value)} placeholder="-1001234567890" className="font-mono text-[0.82rem]" />
          </Field>

          <div className="flex items-center gap-3 flex-wrap rounded-md border border-dashed border-nb-gray-200 dark:border-nb-gray-800 px-3.5 py-3">
            <Button variant="secondary" onClick={onAutoTopics} disabled={save.isPending || createTopics.isPending || noConn}>
              <Layers size={14} /> {createTopics.isPending ? 'Creating…' : 'Auto-create topics'}
            </Button>
            <span className="text-[0.78rem] text-nb-gray-500 dark:text-nb-gray-400 flex-1 min-w-[220px]">
              Creates a forum topic per category in the group and fills the Topic IDs below. The bot must be a group admin with the <span className="font-medium">“Manage Topics”</span> permission. Categories that already have an ID are skipped.
            </span>
          </div>

          {/* App-action categories → topics */}
          <div>
            <h3 className="text-sm font-semibold text-nb-gray-800 dark:text-nb-gray-100">App Actions → Topics</h3>
            <p className="text-nb-gray-500 text-[0.8rem] mt-0.5 mb-2">Pick which categories to notify on, and the Topic (thread) ID each routes to. Empty topic = the group's General topic.</p>
            <div className="rounded-md border border-nb-gray-200 dark:border-nb-gray-800 divide-y divide-nb-gray-100 dark:divide-nb-gray-900">
              {TG_CATEGORIES.map((c) => (
                <div key={c.key} className="flex items-center gap-3 px-3 py-2.5">
                  <input type="checkbox" className="h-4 w-4 accent-netbird shrink-0" checked={!!cats[c.key]?.enabled} onChange={(e) => setCat(c.key, { enabled: e.target.checked })} />
                  <span className="flex-1 text-sm text-nb-gray-800 dark:text-nb-gray-200 min-w-0">{c.label}</span>
                  <SourceTag kind="app" />
                  <input value={cats[c.key]?.topic || ''} onChange={(e) => setCat(c.key, { topic: e.target.value })} placeholder="Topic ID" className={topicInputCls} />
                </div>
              ))}
            </div>
          </div>

          {/* NetBird events → topics, split by kind */}
          <div>
            <h3 className="text-sm font-semibold text-nb-gray-800 dark:text-nb-gray-100">NetBird Events → Topics</h3>
            <p className="text-nb-gray-500 text-[0.8rem] mt-0.5 mb-2">NetBird activity is split into a topic per kind. Set a Topic ID for each, and check which event types to forward. The list reflects the types seen so far.</p>
            <div className="rounded-md border border-nb-gray-200 dark:border-nb-gray-800 divide-y divide-nb-gray-100 dark:divide-nb-gray-900">
              {TG_NB_CATEGORIES.map((c) => {
                const evs = eventsByCat[c.key] || [];
                return (
                  <div key={c.key} className="px-3 py-2.5">
                    <div className="flex items-center gap-3">
                      <span className="flex-1 min-w-0 text-sm font-medium text-nb-gray-800 dark:text-nb-gray-100">{c.label}</span>
                      <input value={cats[c.key]?.topic || ''} onChange={(e) => setCat(c.key, { topic: e.target.value })} placeholder="Topic ID" className={topicInputCls} />
                    </div>
                    {evs.length ? (
                      <div className="mt-2 flex flex-col gap-1">
                        {evs.map((t) => (
                          <label key={t.message} className="flex items-center gap-2.5 cursor-pointer">
                            <input type="checkbox" className="h-4 w-4 accent-netbird shrink-0" checked={events.includes(t.message)} onChange={() => toggleEvent(t.message)} />
                            <span className="flex-1 min-w-0 truncate text-[0.82rem] text-nb-gray-700 dark:text-nb-gray-300">{t.message}</span>
                            <SourceTag kind="netbird" />
                            <span className="shrink-0 text-[0.7rem] text-nb-gray-400">{t.count}</span>
                          </label>
                        ))}
                      </div>
                    ) : (
                      <p className="mt-1.5 text-[0.76rem] text-nb-gray-400 dark:text-nb-gray-500">No events of this kind seen yet.</p>
                    )}
                  </div>
                );
              })}
            </div>
          </div>

          <p className="text-[0.82rem] text-nb-gray-500">
            Who may <b>approve access requests</b> (and the separate approvals group) is configured under the <b>Approvals</b> tab.
          </p>

          <div className="flex items-center gap-3 flex-wrap">
            <Button variant="primary" onClick={onSave} disabled={save.isPending}>{save.isPending ? 'Saving…' : 'Save'}</Button>
            <Button variant="secondary" onClick={onTest} disabled={save.isPending || test.isPending || noConn}>
              <Send size={14} /> {test.isPending ? 'Sending…' : 'Send test'}
            </Button>
            {saved && <span className="text-sm text-green-600 dark:text-green-500">Saved</span>}
            {testMsg && <span className="text-sm text-nb-gray-600 dark:text-nb-gray-300">{testMsg}</span>}
            {error && <span className="text-sm text-red-500">{error}</span>}
          </div>
        </div>
      )}
    </div>
  );
}
